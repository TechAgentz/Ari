"use client";

import { CloudOff, Sparkles } from "lucide-react";
import { usesRemoteAI } from "@/lib/agent/client";
import { settingsStore } from "@/lib/storage";
import { useServerConfig } from "@/lib/use-server-config";
import { Badge } from "./ui/primitives";

/** Shows which engine is answering: Groq (with model) or the on-device demo. */
export function ProviderBadge({ mode = "chat" }: { mode?: "chat" | "voice" }) {
  const settings = settingsStore.useValue();
  const { config, loading } = useServerConfig();
  if (loading) return <Badge>Checking…</Badge>;
  if (usesRemoteAI(settings, config)) {
    const model = (mode === "voice" ? config?.voiceModel : config?.model) ?? "";
    return (
      <Badge tone="primary" title={`Replies generated by Groq (${model})`}>
        <Sparkles className="h-3.5 w-3.5 text-primary" />
        Groq · {model.replace(/^openai\//, "")}
      </Badge>
    );
  }
  return (
    <Badge title="GROQ_API_KEY isn't set on the server">
      <CloudOff className="h-3.5 w-3.5" />
      Groq not configured
    </Badge>
  );
}
