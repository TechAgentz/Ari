"use client";

import { LIMITS } from "../config";
import { redactPII } from "../privacy/redact";
import { assessTurnRisk, crisisReply, withholdCrisisMessages } from "../safety/crisis";
import type { ChatMessage, MessageMeta, ReplyEvent, ServerConfig, Settings } from "../types";
import { generateDemoReply } from "./demo-engine";
import { progressFromState, sanitizeMemory, type ChatRequestBody } from "./protocol";
import { analyzeConversation } from "./state";

export interface ReplyResult {
  text: string;
  meta: MessageMeta;
}

interface StreamOptions {
  messages: ChatMessage[];
  mode: "chat" | "voice";
  settings: Settings;
  config: ServerConfig | null;
  signal: AbortSignal;
  onMeta?: (meta: MessageMeta) => void;
  onDelta: (text: string) => void;
}

/** Whether replies will be generated by the remote AI provider (vs. on-device demo engine). */
export function usesRemoteAI(settings: Settings, config: ServerConfig | null): boolean {
  return settings.aiMode === "auto" && settings.consent.ai && !!config?.groqConfigured;
}

const sleep = (ms: number, signal: AbortSignal) =>
  new Promise<void>((resolve) => {
    const t = setTimeout(resolve, ms);
    signal.addEventListener("abort", () => {
      clearTimeout(t);
      resolve();
    });
  });

/** Types out a ready reply after a short "thinking" pause, like a streamed one. */
async function typeOut(opts: StreamOptions, reply: ReplyResult): Promise<ReplyResult> {
  opts.onMeta?.(reply.meta);
  await sleep(350 + Math.random() * 350, opts.signal);
  let text = "";
  for (const part of reply.text.match(/\S+\s*/g) ?? [reply.text]) {
    if (opts.signal.aborted) break;
    text += part;
    opts.onDelta(part);
    await sleep(14 + Math.min(40, part.length * 3), opts.signal);
  }
  return { text, meta: reply.meta };
}

function streamLocal(opts: StreamOptions, extra?: Partial<MessageMeta>): Promise<ReplyResult> {
  const state = analyzeConversation(opts.messages);
  const reply = generateDemoReply(opts.messages, state, opts.mode);
  return typeOut(opts, { text: reply.text, meta: { ...reply.meta, ...extra } });
}

/**
 * Produces the companion's next reply, streaming deltas as they arrive.
 * Messages are redacted and trimmed to a recent window before leaving the device;
 * personal context is only included with explicit consent.
 */
export async function streamReply(opts: StreamOptions): Promise<ReplyResult> {
  // Crisis disclosures, and a "yes" to a safety check, get the deterministic crisis
  // response right here: they never leave the device.
  const risk = assessTurnRisk(opts.messages);
  if (risk.level === "crisis") return typeOut(opts, crisisReply(risk.categories, opts.mode));
  if (!usesRemoteAI(opts.settings, opts.config)) return streamLocal(opts);

  // Earlier crisis disclosures and the replies to them are withheld too (placeholders keep the
  // conversation's shape). Memory is derived from the same redacted, withheld text.
  const safe = withholdCrisisMessages(opts.messages.map((m) => ({ ...m, content: redactPII(m.content) })));
  const state = analyzeConversation(safe);
  const window = safe.slice(-LIMITS.contextWindow);
  const body: ChatRequestBody = {
    mode: opts.mode,
    messages: window.map((m) => ({
      role: m.role,
      content: m.content.slice(0, LIMITS.maxMessageChars),
      meta: {
        topic: m.meta?.topic,
        questionId: m.meta?.questionId,
        stage: m.meta?.stage,
        techniqueOffered: m.meta?.techniqueOffered,
        techniqueGiven: m.meta?.techniqueGiven,
        strategy: m.meta?.strategy,
        nudge: m.meta?.nudge,
        safety: m.meta?.safety,
      },
    })),
    progress: progressFromState(state),
    shareContext: opts.settings.consent.context,
    memory: opts.settings.consent.context ? sanitizeMemory(state.memory) : undefined,
  };

  let res: Response;
  try {
    res = await fetch("/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
      signal: opts.signal,
    });
  } catch (err) {
    if (opts.signal.aborted) return { text: "", meta: { interrupted: true } };
    console.warn("Chat request failed, using on-device demo", err);
    return streamLocal(opts, { fallback: true, fallbackReason: "offline" });
  }
  if (!res.ok || !res.body) {
    return streamLocal(opts, { fallback: true, fallbackReason: res.status === 429 ? "rate-limit" : "server" });
  }

  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let buffer = "";
  let text = "";
  let meta: MessageMeta = {};
  // The server lost the AI provider mid-reply: what arrived is incomplete.
  let failed = false;
  try {
    while (true) {
      const { value, done } = await reader.read();
      if (done) break;
      buffer += decoder.decode(value, { stream: true });
      let nl: number;
      while ((nl = buffer.indexOf("\n")) >= 0) {
        const line = buffer.slice(0, nl).trim();
        buffer = buffer.slice(nl + 1);
        if (!line) continue;
        let event: ReplyEvent;
        try {
          event = JSON.parse(line) as ReplyEvent;
        } catch {
          continue;
        }
        if (event.type === "meta") {
          meta = event.meta;
          opts.onMeta?.(meta);
        } else if (event.type === "delta") {
          text += event.text;
          opts.onDelta(event.text);
        } else if (event.type === "done" && event.meta) {
          meta = { ...meta, ...event.meta };
        } else if (event.type === "error") {
          failed = true;
        }
      }
    }
  } catch (err) {
    if (!opts.signal.aborted) console.warn("Stream interrupted", err);
    return { text, meta: { ...meta, interrupted: true } };
  }
  if (!text.trim()) return streamLocal(opts, { fallback: true, fallbackReason: failed ? "server" : "empty" });
  // A cut-off reply is marked, so it isn't saved or spoken as a complete answer (and asks nothing).
  if (failed || meta.interrupted) return { text, meta: { ...meta, interrupted: true, topic: undefined, techniqueOffered: undefined, questionId: undefined, techniqueGiven: undefined } };
  return { text, meta };
}
